static const uint8_t *glyph(char c) {
  if (c >= 'a' && c <= 'z' && c != 'x') c -= 32;
  for (size_t i = 0; i < sizeof font / sizeof font[0]; i++)
    if (font[i].c == c) return font[i].rows;
  return NULL;
}

#define CW 6 /* glyph cell: 5 px + 1 px spacing */
#define CH 9 /* 7 px + 2 px line gap */
#define PAD 3

static GLuint prog, tex;
static GLint u_rect;
static int tex_w, tex_h;
static char shown[512];

static void rasterise(const char *text) {
  int cols = 0, lines = 1, col = 0;
  for (const char *p = text; *p; p++) {
    if (*p == '\n') lines++, col = 0;
    else if (++col > cols) cols = col;
  }
  tex_w = cols * CW + PAD * 2 - 1;
  tex_h = lines * CH + PAD * 2 - 2;
  uint8_t *px = calloc((size_t)tex_w * tex_h, 4);
  for (int i = 0; i < tex_w * tex_h; i++) px[i * 4 + 3] = 170; /* translucent black panel */
  int x = 0, line = 0;
  for (const char *p = text; *p; p++) {
    if (*p == '\n') {
      line++, x = 0;
      continue;
    }
    const uint8_t *g = glyph(*p);
    for (int r = 0; g && r < 7; r++)
      for (int c = 0; c < 5; c++) {
        if (!(g[r] >> (4 - c) & 1)) continue;
        int tx = PAD + x * CW + c, ty = PAD + line * CH + r; /* ty counts from the top */
        uint8_t *d = px + ((size_t)ty * tex_w + tx) * 4;
        d[0] = d[1] = d[2] = d[3] = 255;
      }
    x++;
  }
  if (!tex) glGenTextures(1, &tex);
  glBindTexture(GL_TEXTURE_2D, tex);
  glTexImage2D(GL_TEXTURE_2D, 0, GL_RGBA8, tex_w, tex_h, 0, GL_RGBA, GL_UNSIGNED_BYTE, px);
  glTexParameteri(GL_TEXTURE_2D, GL_TEXTURE_MIN_FILTER, GL_NEAREST);
  glTexParameteri(GL_TEXTURE_2D, GL_TEXTURE_MAG_FILTER, GL_NEAREST);
  glTexParameteri(GL_TEXTURE_2D, GL_TEXTURE_WRAP_S, GL_CLAMP_TO_EDGE);
  glTexParameteri(GL_TEXTURE_2D, GL_TEXTURE_WRAP_T, GL_CLAMP_TO_EDGE);
  free(px);
}

/* corner: "top-left", "top-right", "bottom-left" or "bottom-right" */
void lw_overlay_draw(const char *text, const char *corner, int fb_w, int fb_h) {
  if (!prog) {
    const char *fs = "#version 300 es\nprecision mediump float;\n"
                     "uniform sampler2D t; uniform vec4 rect; out vec4 o;\n"
                     "void main(){ vec2 uv = (gl_FragCoord.xy - rect.xy) / rect.zw; uv.y = 1.0 - uv.y;\n"
                     "  vec4 c = texture(t, uv); o = vec4(c.rgb * c.a, c.a); }\n";
    prog = lw_gl_program(lw_vs_fullscreen, fs, NULL, 0);
    if (!prog) return;
    u_rect = glGetUniformLocation(prog, "rect");
    glUseProgram(prog);
    glUniform1i(glGetUniformLocation(prog, "t"), 0);
  }
  if (strcmp(text, shown)) {
    snprintf(shown, sizeof shown, "%s", text);
    rasterise(text);
  }
  int s = fb_h / 450 > 1 ? fb_h / 450 : 1; /* integer zoom keeps the pixels crisp */
  int w = tex_w * s, h = tex_h * s, m = 8 * s;
  int x = strstr(corner, "right") ? fb_w - w - m : m;
  int top = m + fb_h * 45 / 1000; /* clear of the Omarchy bar, which the wallpaper extends under */
  int y = strstr(corner, "bottom") ? m : fb_h - h - top;
  glBindFramebuffer(GL_FRAMEBUFFER, 0);
  glViewport(x, y, w, h);
  glUseProgram(prog);
  glUniform4f(u_rect, (float)x, (float)y, (float)w, (float)h);
  glActiveTexture(GL_TEXTURE0);
  glBindTexture(GL_TEXTURE_2D, tex);
  glEnable(GL_BLEND);
  glBlendFunc(GL_ONE, GL_ONE_MINUS_SRC_ALPHA);
  glDrawArrays(GL_TRIANGLES, 0, 3);
  glDisable(GL_BLEND);
  glViewport(0, 0, fb_w, fb_h);
}

void lw_overlay_reset(void) { /* after a GL context change */
  prog = tex = 0;
  shown[0] = 0;
}
